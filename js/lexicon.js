export function greetingFor(hour) {
  if (hour >= 5 && hour < 9)  return '晨 · 雾气还没散，正好躲进来';
  if (hour >= 9 && hour < 12) return '上午 · 偷得浮生半刻闲';
  if (hour >= 12 && hour < 14) return '午 · 饭后的困意是最好的掩护';
  if (hour >= 14 && hour < 17) return '午后 · 阳光斜了，心也斜过来';
  if (hour >= 17 && hour < 19) return '暮 · 夕阳打卡处，情绪寄存处';
  if (hour >= 19 && hour < 23) return '夜 · 夜游神正式营业';
  return '深夜 · 这个点还醒着的人，都有故事';
}

// 工具：数组按种子取
export function pick(arr, seed) {
  return arr[Math.abs(Math.floor(seed)) % arr.length];
}
export function pickN(arr, n, seed) {
  const used = new Set(); const out = [];
  let s = Math.abs(Math.floor(seed));
  while (out.length < n && used.size < arr.length) {
    const i = s % arr.length;
    if (!used.has(i)) { used.add(i); out.push(arr[i]); }
    s = s * 7 + 13;
  }
  return out;
}

